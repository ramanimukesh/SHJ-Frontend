/**
 * Generates src/data/techIcons.js — the brand SVG paths used by the technology
 * ecosystem on /technology.
 *
 * The paths are baked into a data file rather than importing `simple-icons` at
 * runtime: the site needs ~60 of its 3000+ marks, and inlining the `d` strings
 * keeps the icon payload proportional to what is actually rendered.
 *
 * Re-run with `node scripts/gen-tech-icons.js` after editing MAP.
 *
 * Marks simple-icons no longer ships (AWS, Azure, Oracle, SQL Server, Magento,
 * Playwright, C#, Adobe XD, Photoshop, DynamoDB, Azure DevOps — removed under
 * its trademark policy) are not listed here. Those are served as static SVGs
 * from public/img/tech/ (Devicon, MIT) via the `logo` field in stack.js. The
 * two with no redistributable mark at all (OpenAI, Power BI) use a drawn glyph
 * in the vendor's colour — see TechIcon.jsx.
 */
const fs = require("fs");
const path = require("path");
const si = require("simple-icons");

// our key -> simple-icons slug
const MAP = {
  angular: "angular", react: "react", nextjs: "nextdotjs", vue: "vuedotjs",
  nuxt: "nuxt", typescript: "typescript", javascript: "javascript",
  html5: "html5", css3: "css", tailwind: "tailwindcss", bootstrap: "bootstrap",

  java: "openjdk", springboot: "springboot", python: "python", django: "django",
  fastapi: "fastapi", nodejs: "nodedotjs", express: "express", dotnet: "dotnet",
  php: "php", laravel: "laravel", graphql: "graphql",

  android: "android", kotlin: "kotlin", ios: "ios", swift: "swift",
  reactnative: "react", flutter: "flutter",

  tensorflow: "tensorflow", pytorch: "pytorch", langchain: "langchain",
  huggingface: "huggingface",

  postgresql: "postgresql", mysql: "mysql", mongodb: "mongodb", redis: "redis",
  firebase: "firebase", sqlite: "sqlite",

  googlecloud: "googlecloud", docker: "docker", kubernetes: "kubernetes",

  git: "git", github: "github", gitlab: "gitlab", jenkins: "jenkins",
  githubactions: "githubactions", terraform: "terraform",

  selenium: "selenium", cypress: "cypress", junit: "junit5", pytest: "pytest",
  jest: "jest", postman: "postman", jmeter: "apachejmeter", appium: "appium",

  wordpress: "wordpress", shopify: "shopify", woocommerce: "woocommerce",
  drupal: "drupal",

  pandas: "pandas", numpy: "numpy", jupyter: "jupyter",

  figma: "figma",
};

const out = {};
const missing = [];
for (const [key, slug] of Object.entries(MAP)) {
  const icon = si["si" + slug.charAt(0).toUpperCase() + slug.slice(1)];
  if (!icon) { missing.push(`${key} (${slug})`); continue; }
  out[key] = { p: icon.path, c: "#" + icon.hex };
}

if (missing.length) {
  console.error("Unresolved simple-icons slugs:\n  " + missing.join("\n  "));
  process.exit(1);
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${/^[a-z][a-z0-9]*$/i.test(k) ? k : JSON.stringify(k)}: {\n    c: ${JSON.stringify(v.c)},\n    p: ${JSON.stringify(v.p)},\n  },`)
  .join("\n");

const file = `/* GENERATED by scripts/gen-tech-icons.js — do not edit by hand.
 *
 * Brand marks from simple-icons (CC0-1.0). \`p\` is the 24x24 path, \`c\` the
 * brand colour, which the grid only reveals on hover — see TechIcon.jsx.
 */
const ICONS = {
${body}
};

export default ICONS;
`;

const dest = path.join(__dirname, "..", "src", "data", "techIcons.js");
fs.writeFileSync(dest, file);
console.log(`wrote ${dest} — ${Object.keys(out).length} marks, ${(file.length / 1024).toFixed(1)} kB`);
